function t(lang) {
  const d = dict[lang] || dict[DEFAULT_LANG];
  return (key) => (key in d ? d[key] : key);
}

// "27 қазан 2026" / "27 октября 2026"
function formatDate(value, lang) {
  if (!value) return '';
  const d = new Date(String(value).replace(' ', 'T') + (String(value).includes('Z') ? '' : 'Z'));
  if (Number.isNaN(d.getTime())) return '';
  const local = new Date(d.getTime() + 5 * 3600 * 1000); // Atyrau time, UTC+5
  const m = dict[lang].months[local.getUTCMonth()];
  return lang === 'kk'
    ? `${local.getUTCFullYear()} ж. ${local.getUTCDate()} ${m}`
    : `${local.getUTCDate()} ${m} ${local.getUTCFullYear()}`;
}

// Picks the field for the current language, falling back to the other language.
function pick(obj, field, lang) {
  if (!obj) return '';
  const own = obj[`${field}_${lang}`];
  if (own && String(own).trim()) return own;
  const other = obj[`${field}_${lang === 'kk' ? 'ru' : 'kk'}`];
  return other || '';
}

